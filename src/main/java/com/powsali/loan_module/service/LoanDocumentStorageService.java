package com.powsali.loan_module.service;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.UUID;

@Service
public class LoanDocumentStorageService {

    private final Path storageRoot;

    public LoanDocumentStorageService(
            @Value("${app.documents.storage-dir:./uploads/loan-documents}") String storageDirectory) {
        this.storageRoot = Path.of(storageDirectory).toAbsolutePath().normalize();
    }

    public String store(byte[] content, String extension) throws IOException {
        Files.createDirectories(storageRoot);
        String storedFilename = UUID.randomUUID() + extension;
        Path target = resolve(storedFilename);
        Files.write(target, content, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
        return storedFilename;
    }

    public Path resolve(String storedFilename) {
        // Stored names are generated by the server, never copied from client input.
        if (storedFilename == null || !storedFilename.matches(
                "[0-9a-fA-F-]{36}\\.(pdf|jpg|jpeg|png)")) {
            throw new IllegalArgumentException("Invalid stored document reference");
        }
        Path target = storageRoot.resolve(storedFilename).normalize();
        if (!target.startsWith(storageRoot)) {
            throw new IllegalArgumentException("Invalid document path");
        }
        return target;
    }

    public void deleteQuietly(String storedFilename) {
        try {
            Files.deleteIfExists(resolve(storedFilename));
        } catch (IOException | IllegalArgumentException exception) {
            // Cleanup must not hide the original persistence/storage error.
        }
    }
}
